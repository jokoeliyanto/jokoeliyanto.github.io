"""Sync the home page (_pages/about.md) with the GitHub profile README.

Source: https://github.com/jokoeliyanto/jokoeliyanto/blob/main/README.md

Relative image/link paths in the README are rewritten to absolute URLs on
raw.githubusercontent.com so they keep working on jokoeliyanto.github.io.

Usage:
    python scripts/sync_readme.py                 # fetch README from GitHub
    python scripts/sync_readme.py path/README.md  # use a local README
"""
import re
import sys
import urllib.request
from pathlib import Path

REPO = "jokoeliyanto/jokoeliyanto"
BRANCH = "main"
RAW_BASE = f"https://raw.githubusercontent.com/{REPO}/{BRANCH}/"
OUTPUT = Path(__file__).resolve().parent.parent / "_pages" / "about.md"

FRONT_MATTER = """---
permalink: /
title: "About Me"
author_profile: true
redirect_from:
  - /about/
  - /about.html
---

<!-- This page is generated by scripts/sync_readme.py from
     https://github.com/jokoeliyanto/jokoeliyanto/blob/main/README.md
     Edit the README there instead of this file. -->

"""


def is_relative(url):
    return not re.match(r"^([a-zA-Z][a-zA-Z0-9+.-]*:|//|#|/)", url)


def absolutize(url):
    return RAW_BASE + url.lstrip("./") if is_relative(url) else url


def convert(readme):
    # HTML attributes: src="..." / href="..."
    readme = re.sub(
        r'\b(src|href)="([^"]+)"',
        lambda m: f'{m.group(1)}="{absolutize(m.group(2))}"',
        readme,
    )
    # Markdown links and images: [text](url) / ![alt](url)
    readme = re.sub(
        r"(!?\[[^\]]*\]\()([^)\s]+)",
        lambda m: m.group(1) + absolutize(m.group(2)),
        readme,
    )
    # Keep Liquid from interpreting any {{ }} / {% %} in the README
    return FRONT_MATTER + "{% raw %}\n" + readme.strip() + "\n{% endraw %}\n"


def main():
    if len(sys.argv) > 1:
        readme = Path(sys.argv[1]).read_text(encoding="utf-8")
    else:
        with urllib.request.urlopen(RAW_BASE + "README.md") as resp:
            readme = resp.read().decode("utf-8")
    OUTPUT.write_text(convert(readme), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
